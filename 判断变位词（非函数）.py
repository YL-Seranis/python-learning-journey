"""
--------------------------------------------------------------------------
题目：判断变位词
    变位词，即由相同的字母以不同的顺序组成的单词。例如：listen和 silent就是变位词。
    定义一个函数 are_anagrams(s1, s2)，检查两个字符串 s1 和 s2是否是变位词，返回 True或 False。
注意：字符串大小写无关，字符串前后多余空格不能影响变位词判断。短语中间的空格也不能影响变位词判断。
    编写测试代码，接收用户输入的两个字符串，判断是否是变位词，打印输出结果。
示例1：
请输入第1个字符串:listen
请输入第2个字符串:silent
True
示例2：
请输入第1个字符串:dormitory
请输入第2个字符串:dirty room
True
示例3：
请输入第1个字符串:listen
请输入第2个字符串:silence
False
思路说明：
先去掉空格符，并统一变成大写（或小写）后再判断
两个字符串是变位词关系，必须含有相同的字母，并且每个字母数量相同。 所以在比对时，要检测是否含有相同的字母；对每个字母检测是否数量相同。
最好的方式是，对字符串中所有字符按统一的规则排序，排序后两个字符串相同，则两个原始字符串为变位词。
--------------------------------------------------------------------------
"""
#**********Program**********
s1 = input("请输入第1个字符串:")
s2 = input("请输入第1个字符串:")

s1 = s1.replace(' ', '')
s2 = s2.replace(' ', '')

s1 = s1.lower()
s2 = s2.lower()

s1 = sorted(s1)
s2 = sorted(s2)

if s1 == s2:
    print(True)
else:
    print(False)
