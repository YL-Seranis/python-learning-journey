"""
--------------------------------------------------------------------------
题目：合并两个有序列表
    定义一个函数 merge_sorted_list(list1, list2), 该函数接收两个非递减顺序的列表list1, list2，并且合并后的列表同样按非递减顺序排列。该函数返回合并后的列表。
    编写代码，分两行接收用户输入的两组数据（没有排序的，以空格分隔），先将两组数据分别按非递减顺序排列，然后调用上述函数，输出合并后的列表。要求在排序操作时不要使用额外空间。
示例 ：
输入：
1 3 5 7
2 4 6 8
输出：
[1, 2, 3, 4, 5, 6, 7, 8]
--------------------------------------------------------------------------
思路：
定义函数，实现将第二个列表拼接到第一个列表，并对第一个列表排序，返回第一个列表。
主函数输入两个列表，调用函数完成功能。
--------------------------------------------------------------------------
"""
#**********Program**********
list_0 = input().strip().split()
list_1 = []
for i in list_0:    # 字符串1变成整数，存入list_1
    # 用append一个个往里边加
    list_1.append(int(i))
list_1.sort()

list_2 = input().strip().split()
list_3 = []
for i in list_2:    # 字符串1变成整数，存入list_2
    # 用append一个个往里边加
    list_3.append(int(i))
list_3.sort()       # 对新的列表进行排序
# 把list_1连接在list_0后面
list_1.extend(list_3)
list_1.sort()

print(list_1)


#**********End**************