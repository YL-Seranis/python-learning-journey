"""
--------------------------------------------------------------------------
题目：数字拆分
    将 324 分拆成 w,x,y,z四个正整数，即四个正整数之和等于324 。
    且 w加上2，x减去2，y乘以2， z除以2，
这4个结果是相等的。 编写程序求出这四个正整数，
并按如下格式打印这四个正整数：w=某数,x=某数,y=某数,z=某数
--------------------------------------------------------------------------
"""
#**********Program**********
# 定义变量
T = 324 * 2 // 9
w = T - 2
x = T + 2
y = T // 2
z = T * 2
# 将和式变成只含T的方程
if (T + 2) + (T - 2) + (T * 2) + (T // 2) == 324:
    print(f"w={w},x={x},y={y},z={z}")
"""
右边 324 不变。左边这四项每一项里面都有 T，我们把它收拢一下：

第一项 T − 2：T 有 1 个
第二项 T + 2：T 有 1 个（那个 +2 和前面的 −2 正好抵消，所以剩下的就是 T）
第三项 T ÷ 2：也就是 0.5 个 T
第四项 T × 2：也就是 2 个 T

所以方程就是：
4.5 × T = 324
"""
#**********End**************
