"""
--------------------------------------------------------------------------
题目：轮转列表
    定义一个函数 rotate(nums, k)，接收一个整数列表 nums，将列表中的元素向右轮转 k个位置，其中 k 是非负数。函数返回轮转后的列表。向右轮转是指将列表末尾的 k 个元素按原顺序移动到列表的最前面，而列表中原来的元素则整体向后顺延。例如：对于列表 [1, 2, 3, 4, 5]，向右轮转 2 个位置后，末尾的 4, 5 会被移到最前面，结果变为 [4, 5, 1, 2, 3]。
    编写代码，接收键盘输入数据，调用上述函数，输出轮转后的列表。第一行接收用户输入的一组数据， 以英文逗号（,）分隔，第二行接收用户输入的k值。
    假设输入合法无需校验。
示例1：
输入：
1,2,3,4,5,6,7
3
输出：
[5, 6, 7, 1, 2, 3, 4]

示例2：
输入：
1,2,3,4
6
输出：
[3, 4, 1, 2]
--------------------------------------------------------------------------
思路：
输入字符串，去除首尾的空格，并分裂成列表。
输入转轮转动的格数k，并按列表实际长度，取模，计算列表实际右移格数。
列表中数字按转轮右移，实际上是重新分组、组合，可以采用切片、拼接实现。
--------------------------------------------------------------------------
"""
#**********Program**********
nums = input().strip().split()  # 输入字符串，去除首尾的空格，并分裂成列表
# 把每一串字符变成整数
nums = [int(i) for i in nums]
k = int(input())    # 输入转轮转动的格数
k %= len(nums)
nums_g = nums[-k:] + nums[:-k]

print(nums_g)


